def average_grade(a, b, c): #функция для поиска среднего балла
    return (a + b + c) / 3 #складываем 3 оценки и делим на 3
def grade_message(average): #функция которая подбирает текст по баллу
    if average >= 4.5: #если балл от 4.5 и выше
        return "Отлично" #возвращаем отлично
    elif average >= 3.5: #если от 3.5 до 4.5
        return "Хорошо" #возвращаем хорошо
    else: #во всех остальных случаях
        return "Нужно повторить материал" #возвращаем этот текст
lol = average_grade(5, 4, 5) #считаем средний балл для 5, 4, 5
print(f"Средний балл: {lol}") #выводим первый балл
print(grade_message(lol)) #выводим сообщение для первого балла
lil = average_grade(3, 4, 3) #считаем средний балл для 3, 4, 3
print(f"Средний балл: {lil}") #выводим второй балл
print(grade_message(lil)) #выводим сообщение для второго балла


    
    